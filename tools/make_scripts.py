"""Stage 3: assemble the self-contained Rhino build script and Grasshopper component.

Each output = verified spec (embedded JSON) + geometry core + RhinoCommon adapter + entry point,
so the Rhino script runs in ONE MCP call and the Grasshopper component needs no extra files.
Edit the sources (spec, core, adapter, *_main.py), never the generated files.
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def read(*parts):
    with open(os.path.join(ROOT, *parts)) as fh:
        return fh.read()


def strip_header(src):
    """Drop the coding line and the module docstring so concatenated parts read cleanly."""
    src = re.sub(r"^# -\*- coding: utf-8 -\*-\n", "", src)
    return re.sub(r'^\s*"""(.|\n)*?"""\n', "", src, count=1)


def assemble(title, main_parts):
    spec = json.loads(read("spec", "pavilion_spec.json"))
    spec["meta"].pop("views", None)  # cameras and anchors: extraction data, not needed to build
    spec_src = json.dumps(spec, separators=(",", ":"))
    return "\n".join([
        "#! python3",
        "# -*- coding: utf-8 -*-",
        "# " + title,
        "# GENERATED by tools/make_scripts.py from spec/pavilion_spec.json + core/mvm_core.py + rhino/rhino_adapter.py.",
        "# Do not edit: change the sources and regenerate.",
        "import json",
        "",
        "SPEC = json.loads(r'''" + spec_src + "''')",
        "",
        "# ======== core/mvm_core.py ========",
        strip_header(read("core", "mvm_core.py")),
        "# ======== rhino/rhino_adapter.py ========",
        strip_header(read("rhino", "rhino_adapter.py")),
    ] + main_parts)


def main():
    targets = [
        (("rhino", "mvm_build_rhino.py"), "MVM Canopy Pavilion - Rhino build script (single MCP call / ScriptEditor)",
         ["# ======== rhino/build_main.py ========", strip_header(read("rhino", "build_main.py"))]),
        (("grasshopper", "mvm_pavilion_gh.py"), "MVM Canopy Pavilion - Grasshopper Script component (parametric)",
         ["# ======== grasshopper/gh_main.py ========", strip_header(read("grasshopper", "gh_main.py"))]),
    ]
    for parts, title, main_parts in targets:
        src = assemble(title, main_parts)
        compile(src, parts[-1], "exec")
        with open(os.path.join(ROOT, *parts), "w") as fh:
            fh.write(src)
        print("wrote", os.path.join(*parts), len(src) // 1024, "KB")


if __name__ == "__main__":
    main()
