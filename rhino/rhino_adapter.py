# -*- coding: utf-8 -*-
"""RhinoCommon adapter: core primitives -> Rhino geometry. Shared by the Rhino build script and
the Grasshopper component (both are generated by tools/make_scripts.py). IronPython 2.7 / Python 3."""
import math

import Rhino
import Rhino.Geometry as rg
import System
from System.Collections.Generic import List


def _pt(p, k):
    return rg.Point3d(p[0] * k, p[1] * k, p[2] * k)


def _pts(pts, k, close=False):
    out = List[rg.Point3d]()
    for p in pts:
        out.Add(_pt(p, k))
    if close:
        out.Add(_pt(pts[0], k))
    return out


def to_rhino(prim, k, tol):
    """One primitive -> list of Rhino geometry, scaled by k (mm -> model units)."""
    kind = prim["kind"]
    if kind == "mesh":
        m = rg.Mesh()
        for v in prim["v"]:
            m.Vertices.Add(v[0] * k, v[1] * k, v[2] * k)
        for f in prim["f"]:
            if len(f) == 3:
                m.Faces.AddFace(f[0], f[1], f[2])
            else:
                m.Faces.AddFace(f[0], f[1], f[2], f[3])
        m.Normals.ComputeNormals()
        m.Compact()
        return [m]
    if kind == "lines":
        return [rg.LineCurve(_pt(a, k), _pt(b, k)) for a, b in prim["segs"]]
    if kind == "polyline":
        return [rg.PolylineCurve(_pts(prim["pts"], k, prim.get("closed", False)))]
    if kind == "pipe":
        pts = _pts(prim["pts"], k)
        if pts.Count == 2:
            rail = rg.LineCurve(pts[0], pts[1])
        else:
            rail = rg.Curve.CreateInterpolatedCurve(pts, 3)
        params = List[float]()
        params.Add(rail.Domain.Min)
        params.Add(rail.Domain.Max)
        radii = List[float]()
        radii.Add(prim["r"][0] * k)
        radii.Add(prim["r"][1] * k)
        breps = rg.Brep.CreatePipe(rail, params, radii, True, rg.PipeCapMode.Flat, True, tol, math.radians(1.0))
        return list(breps) if breps else [rail]
    if kind == "extrude":
        closed = prim.get("closed", True)

        def loop(pts, smooth):
            if closed and smooth:
                return rg.Curve.CreateInterpolatedCurve(_pts(pts, k), 3, rg.CurveKnotStyle.ChordPeriodic)
            return rg.PolylineCurve(_pts(pts, k, closed))
        crv = loop(prim["pts"], prim.get("smooth", False))
        vec = rg.Vector3d(prim["vec"][0] * k, prim["vec"][1] * k, prim["vec"][2] * k)
        flags = prim.get("holes_smooth", [])
        holes = [loop(h, flags[i] if i < len(flags) else False) for i, h in enumerate(prim.get("holes", []))]
        if closed and prim.get("cap", True):
            loops = List[rg.Curve]()
            loops.Add(crv)
            for h in holes:
                loops.Add(h)
            planar = rg.Brep.CreatePlanarBreps(loops, tol)
            if planar:
                p0 = crv.PointAtStart
                brep = planar[0].Faces[0].CreateExtrusion(rg.LineCurve(p0, p0 + vec), True)
                if brep:
                    return [brep]
        brep = rg.Surface.CreateExtrusion(crv, vec).ToBrep()
        return [brep]
    raise ValueError("unknown primitive: " + str(kind))


def unit_scale(rdoc):
    return Rhino.RhinoMath.UnitScale(Rhino.UnitSystem.Millimeters, rdoc.ModelUnitSystem)


def color(rgb):
    return System.Drawing.Color.FromArgb(rgb[0], rgb[1], rgb[2])
